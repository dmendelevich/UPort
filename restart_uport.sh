#!/bin/bash

echo "=== Systemd: Тотальный перезапуск монолита UPort ==="

# 1. Принудительно отдаем команду СТОП и ждем пару секунд, пока память полностью очистится
sudo systemctl stop uport.service

# 2. Запускаем новую службу в мгновенном асинхронном режиме без блокировки терминала
sudo systemctl start --no-block uport.service

echo "✅ Монолит UPort успешно перезапущен в чистой памяти!"
echo "Для просмотра живого лога используйте команду: tail -f uport_system.log"
